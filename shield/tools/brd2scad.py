#!/usr/bin/env python3
"""Extract PCB geometry from an Eagle .brd file into an OpenSCAD include.

Usage: brd2scad.py <board.brd> <prefix> <out.scad>

Writes the board outline (layer 20), mounting holes (MOUNT-HOLE* elements)
and every part's position, rotation and footprint box. Coordinates are moved
so the outline's lower-left corner is [0, 0]. Eagle's +Y stays +Y.
"""
import math
import os
import sys
import xml.etree.ElementTree as ET

# Layers that describe a part's footprint: tPlace, tKeepout, tDocu.
FOOTPRINT_LAYERS = {"21", "39", "51"}


def num(el, attr, default=0.0):
    v = el.get(attr)
    return float(v) if v is not None else default


def parse_rot(rot):
    rot = rot or "R0"
    mirror = "M" in rot
    angle = float(rot.lstrip("SM").lstrip("R"))
    return angle, mirror


def package_points(pkg):
    """Points (with radius) that bound a package in its own coordinates."""
    pts = []
    for el in pkg:
        tag, layer = el.tag, el.get("layer")
        if tag == "pad":
            drill = num(el, "drill")
            r = num(el, "diameter", drill * 2) / 2 or drill
            pts.append((num(el, "x"), num(el, "y"), r))
        elif tag == "smd":
            dx, dy = num(el, "dx") / 2, num(el, "dy") / 2
            x, y = num(el, "x"), num(el, "y")
            pts += [(x - dx, y - dy, 0), (x + dx, y + dy, 0)]
        elif tag == "hole":
            pts.append((num(el, "x"), num(el, "y"), num(el, "drill") / 2))
        elif layer not in FOOTPRINT_LAYERS:
            continue
        elif tag == "wire":
            w = num(el, "width") / 2
            pts += [(num(el, "x1"), num(el, "y1"), w), (num(el, "x2"), num(el, "y2"), w)]
        elif tag == "circle":
            pts.append((num(el, "x"), num(el, "y"), num(el, "radius") + num(el, "width") / 2))
        elif tag == "rectangle":
            pts += [(num(el, "x1"), num(el, "y1"), 0), (num(el, "x2"), num(el, "y2"), 0)]
        elif tag == "polygon":
            pts += [(num(v, "x"), num(v, "y"), 0) for v in el.iter("vertex")]
    return pts


def footprint_box(pkg, x, y, angle, mirror):
    a = math.radians(angle)
    c, s = math.cos(a), math.sin(a)
    xs, ys = [], []
    for px, py, r in package_points(pkg):
        if mirror:
            px = -px
        bx, by = x + px * c - py * s, y + px * s + py * c
        xs += [bx - r, bx + r]
        ys += [by - r, by + r]
    if not xs:
        return [x, y, x, y]
    return [min(xs), min(ys), max(xs), max(ys)]


def chain_outline(segments):
    """Order loose layer-20 segments into one closed polygon."""
    segs = list(segments)
    poly = [segs[0][0], segs[0][1]]
    segs.pop(0)
    close = lambda p, q: abs(p[0] - q[0]) < 1e-3 and abs(p[1] - q[1]) < 1e-3
    while segs:
        for i, (a, b) in enumerate(segs):
            if close(a, poly[-1]):
                poly.append(b)
            elif close(b, poly[-1]):
                poly.append(a)
            else:
                continue
            segs.pop(i)
            break
        else:
            sys.exit("board outline on layer 20 is not one closed loop")
    if close(poly[0], poly[-1]):
        poly.pop()
    return poly


def fmt(v):
    return f"{round(v, 3):g}"


def main(brd, prefix, out):
    root = ET.parse(brd).getroot()
    board = root.find(".//board")

    segments = [
        ((num(w, "x1"), num(w, "y1")), (num(w, "x2"), num(w, "y2")))
        for w in board.find("plain").iter("wire")
        if w.get("layer") == "20"
    ]
    if any(w.get("curve") for w in board.find("plain").iter("wire") if w.get("layer") == "20"):
        print("warning: outline has arcs; only their end points are used", file=sys.stderr)
    outline = chain_outline(segments)
    ox = min(p[0] for p in outline)
    oy = min(p[1] for p in outline)
    sx = max(p[0] for p in outline) - ox
    sy = max(p[1] for p in outline) - oy

    packages = {
        (lib.get("name"), pkg.get("name")): pkg
        for lib in board.iter("library")
        for pkg in lib.iter("package")
    }

    holes, parts = [], []
    for el in board.find("elements"):
        x, y = num(el, "x"), num(el, "y")
        angle, mirror = parse_rot(el.get("rot"))
        pkg = packages[(el.get("library"), el.get("package"))]
        value = el.get("value") or ""
        if value.startswith("MOUNT-HOLE"):
            drill = max(num(h, "drill") for h in pkg.iter("hole"))
            holes.append((el.get("name"), x - ox, y - oy, drill))
            continue
        x0, y0, x1, y1 = footprint_box(pkg, x, y, angle, mirror)
        parts.append((el.get("name"), el.get("package"), value, x - ox, y - oy,
                      angle, mirror, [x0 - ox, y0 - oy, x1 - ox, y1 - oy]))

    lines = [
        f"// Generated by shield/tools/brd2scad.py from eagle/{os.path.basename(brd)}. Do not edit; run `make pcb`.",
        "// Units mm. Origin = lower-left corner of the board outline. +Y = Eagle +Y.",
        "",
        f"{prefix}_eagle_origin = [{fmt(ox)}, {fmt(oy)}];",
        f"{prefix}_size = [{fmt(sx)}, {fmt(sy)}];",
        f"{prefix}_outline = [{', '.join(f'[{fmt(px - ox)}, {fmt(py - oy)}]' for px, py in outline)}];",
        "",
        "// [name, x, y, drill]",
        f"{prefix}_holes = [",
        *[f'  ["{n}", {fmt(hx)}, {fmt(hy)}, {fmt(d)}],' for n, hx, hy, d in holes],
        "];",
        "",
        "// [name, package, value, x, y, rot, mirrored, [x0, y0, x1, y1] footprint box]",
        f"{prefix}_parts = [",
        *[
            f'  ["{n}", "{p}", "{v}", {fmt(px)}, {fmt(py)}, {fmt(a)}, {str(m).lower()}, '
            f"[{', '.join(fmt(b) for b in box)}]],"
            for n, p, v, px, py, a, m, box in sorted(parts)
        ],
        "];",
        "",
    ]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
